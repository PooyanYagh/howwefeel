create or replace function public.get_daily_prayer_lines(requested_count integer default 2)
returns setof public.prayer_lines
language sql stable security invoker
as $$
 select p.* from public.prayer_lines p
 where p.is_active
 order by md5(p.id::text || current_date::text || coalesce(auth.uid()::text,''))
 limit greatest(1,least(requested_count,3));
$$;
grant execute on function public.get_daily_prayer_lines(integer) to authenticated;
